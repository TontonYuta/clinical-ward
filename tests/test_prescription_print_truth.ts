import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {PrescriptionPrintDocument, formatPrescriptionQuantity} from '../src/components/RightPane/Tabs/CPOE/PrescriptionPrintDocument';
import type {PrescriptionOrder} from '../src/types/cpoe';
const order:PrescriptionOrder = {id:'RX-TEST',prescriptionType:'outpatient',patientId:'P1',patientName:'Test',patientCccd:'',patientDob:'2022-11-06',patientGender:'',department:'',diagnosisIcd10:'',diagnosisText:'',isChronicDisease:true,daysPrescribed:5,doctorName:'',doctorCertificate:'',prescribedAt:'2026-11-05',status:'draft',items:[{id:'1',medicationName:'Medicine',activeIngredient:'',dosage:'',frequency:'',route:'',quantity:5,unit:'',instructions:''}]};
const html = renderToStaticMarkup(React.createElement(PrescriptionPrintDocument,{order}));
for (const invented of ['Uống sau bữa ăn','BS. Trần Văn Hùng','Số 01 Đường Y Học','024.3825.9999','31/12/2024','90 ngày']) assert.ok(!html.includes(invented), `No invented clinical/legal data: ${invented}`);
assert.ok(html.includes('30/06/2025'));
assert.ok(html.includes('47 tháng'));
assert.equal(formatPrescriptionQuantity(5,true),'05 (năm)');
assert.equal(formatPrescriptionQuantity(21,true),'21 (hai mươi mốt)');
assert.equal(formatPrescriptionQuantity(105,true),'105 (một trăm lẻ năm)');
const signed = renderToStaticMarkup(React.createElement(PrescriptionPrintDocument,{order:{...order,status:'signed',digitalSignature:'unverified'}}));
assert.ok(!signed.includes('✓ ĐÃ KÝ') && !signed.includes('✓ KÝ SỐ'));
const narcotic = renderToStaticMarkup(React.createElement(PrescriptionPrintDocument,{order:{...order,tt26FormType:'PL2_NARCOTIC'}}));
assert.ok(!narcotic.includes('Từ ngày kê đơn đến hết 10 ngày'));
const inpatient = renderToStaticMarkup(React.createElement(PrescriptionPrintDocument,{order:{...order,prescriptionType:'inpatient_daily'}}));
assert.ok(inpatient.includes('Y LỆNH ĐIỀU TRỊ NỘI TRÚ'));
assert.ok(!inpatient.includes('ban hành kèm theo Thông tư số 26'));
console.log('Prescription print factual data checks passed');
